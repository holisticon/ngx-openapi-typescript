import { HttpClient, HttpContext, HttpHeaders, HttpParams } from '@angular/common/http';
import { inject } from '@angular/core';
import type { Observable } from 'rxjs';
import type {
  PathsWithMethod,
  RequestBodyJSON,
  SuccessResponseJSON,
} from 'openapi-typescript-helpers';
import type {
  OpenApiOperationRequest,
  OpenApiRequestOptions,
  OperationParameters,
  PathRecord,
} from './types';
import { buildUrl, toHttpParams } from './url-utils';

/** Configuration for `OpenApiHttpClient` */
export interface OpenApiHttpClientConfig {
  /** Base URL to prepend to all request paths */
  baseUrl?: string;
}

/** Extracts the operation type for a given path and method */
type OpOf<Paths, Path extends keyof Paths, Method extends string> = Paths[Path] extends {
  [K in Method]: infer Op;
}
  ? Op
  : never;

/** Coerces the options to a plain shape */
function toShape(opts: unknown): {
  path?: Record<string, string | number | boolean>;
  query?: Record<string, string | number | boolean | null | undefined>;
  body?: unknown;
  headers?: HttpHeaders | Record<string, string | ReadonlyArray<string>>;
  context?: HttpContext;
  withCredentials?: boolean;
} {
  return ((opts ?? {}) as ReturnType<typeof toShape>);
}

function buildOptions(r: ReturnType<typeof toShape>): {
  responseType: 'json';
  observe: 'body';
  params?: HttpParams;
  headers?: HttpHeaders | Record<string, string | string[]>;
  context?: HttpContext;
  withCredentials?: boolean;
} {
  return {
    responseType: 'json',
    observe: 'body',
    params: toHttpParams(r.query),
    // Cast needed: our public API allows ReadonlyArray<string> (consistent with httpResource),
    // but Angular HttpClient methods require string[].
    headers: r.headers as HttpHeaders | Record<string, string | string[]> | undefined,
    context: r.context,
    withCredentials: r.withCredentials,
  };
}

/**
 * A type-safe HTTP client for OpenAPI-described APIs.
 *
 * Wraps Angular's `HttpClient` and binds request/response types to an OpenAPI
 * schema generated by `openapi-typescript`.
 *
 * Designed to be subclassed per-API:
 *
 * @example
 * ```ts
 * import type { paths } from './api.types'; // generated by openapi-typescript
 *
 * @Injectable({ providedIn: 'root' })
 * export class PetApiClient extends OpenApiHttpClient<paths> {
 *   constructor() {
 *     super({ baseUrl: 'https://api.example.com' });
 *   }
 * }
 * ```
 *
 * Or used directly inside an injection context:
 *
 * @example
 * ```ts
 * const client = new OpenApiHttpClient<paths>({ baseUrl: 'https://api.example.com' });
 * ```
 */
export class OpenApiHttpClient<Paths extends PathRecord> {
  private readonly http = inject(HttpClient);
  private readonly baseUrl: string;

  constructor(config?: OpenApiHttpClientConfig) {
    this.baseUrl = config?.baseUrl ?? '';
  }

  /**
   * Performs a typed GET request.
   *
   * @example
   * ```ts
   * client.get('/pets', { query: { limit: 10 } }).subscribe(pets => console.log(pets));
   * ```
   */
  get<Path extends PathsWithMethod<Paths, 'get'> & keyof Paths>(
    path: Path,
    options?: OperationParameters<NonNullable<OpOf<Paths, Path, 'get'>>> & OpenApiRequestOptions,
  ): Observable<SuccessResponseJSON<NonNullable<OpOf<Paths, Path, 'get'>>>> {
    const r = toShape(options);
    return this.http.get<SuccessResponseJSON<NonNullable<OpOf<Paths, Path, 'get'>>>>(
      buildUrl(this.baseUrl, String(path), r.path),
      buildOptions(r),
    );
  }

  /**
   * Performs a typed POST request.
   */
  post<Path extends PathsWithMethod<Paths, 'post'> & keyof Paths>(
    path: Path,
    options?: OpenApiOperationRequest<NonNullable<OpOf<Paths, Path, 'post'>>>,
  ): Observable<SuccessResponseJSON<NonNullable<OpOf<Paths, Path, 'post'>>>> {
    const r = toShape(options);
    return this.http.post<SuccessResponseJSON<NonNullable<OpOf<Paths, Path, 'post'>>>>(
      buildUrl(this.baseUrl, String(path), r.path),
      r.body as RequestBodyJSON<NonNullable<OpOf<Paths, Path, 'post'>>>,
      buildOptions(r),
    );
  }

  /**
   * Performs a typed PUT request.
   */
  put<Path extends PathsWithMethod<Paths, 'put'> & keyof Paths>(
    path: Path,
    options?: OpenApiOperationRequest<NonNullable<OpOf<Paths, Path, 'put'>>>,
  ): Observable<SuccessResponseJSON<NonNullable<OpOf<Paths, Path, 'put'>>>> {
    const r = toShape(options);
    return this.http.put<SuccessResponseJSON<NonNullable<OpOf<Paths, Path, 'put'>>>>(
      buildUrl(this.baseUrl, String(path), r.path),
      r.body as RequestBodyJSON<NonNullable<OpOf<Paths, Path, 'put'>>>,
      buildOptions(r),
    );
  }

  /**
   * Performs a typed PATCH request.
   */
  patch<Path extends PathsWithMethod<Paths, 'patch'> & keyof Paths>(
    path: Path,
    options?: OpenApiOperationRequest<NonNullable<OpOf<Paths, Path, 'patch'>>>,
  ): Observable<SuccessResponseJSON<NonNullable<OpOf<Paths, Path, 'patch'>>>> {
    const r = toShape(options);
    return this.http.patch<SuccessResponseJSON<NonNullable<OpOf<Paths, Path, 'patch'>>>>(
      buildUrl(this.baseUrl, String(path), r.path),
      r.body as RequestBodyJSON<NonNullable<OpOf<Paths, Path, 'patch'>>>,
      buildOptions(r),
    );
  }

  /**
   * Performs a typed DELETE request.
   */
  delete<Path extends PathsWithMethod<Paths, 'delete'> & keyof Paths>(
    path: Path,
    options?: OpenApiOperationRequest<NonNullable<OpOf<Paths, Path, 'delete'>>>,
  ): Observable<SuccessResponseJSON<NonNullable<OpOf<Paths, Path, 'delete'>>>> {
    const r = toShape(options);
    const httpOptions = buildOptions(r) as { body?: unknown } & ReturnType<typeof buildOptions>;

    if (r.body !== undefined) {
      httpOptions.body = r.body as RequestBodyJSON<NonNullable<OpOf<Paths, Path, 'delete'>>>;
    }

    return this.http.delete<SuccessResponseJSON<NonNullable<OpOf<Paths, Path, 'delete'>>>>(
      buildUrl(this.baseUrl, String(path), r.path),
      httpOptions,
    );
  }
}
