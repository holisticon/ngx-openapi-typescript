import { HttpClient, type HttpHeaders } from '@angular/common/http';
import { inject } from '@angular/core';
import type { PathsWithMethod } from 'openapi-typescript-helpers';
import type { Observable } from 'rxjs';
import type {
  OpenApiHttpRequestOptions,
  OpenApiObserve,
  OpenApiObservedValue,
  OpenApiOperationRequest,
  OpenApiResponseBody,
  OpenApiResponseType,
  PathRecord,
} from './types';
import { buildUrl, toHttpParams } from './url-utils';

/** Configuration for `OpenApiHttpClient` */
export interface OpenApiHttpClientConfig {
  /** Base URL to prepend to all request paths */
  baseUrl?: string;
  /** HTTP client to use instead of injecting Angular's configured HttpClient */
  httpClient?: HttpClient;
}

/** Extracts the operation type for a given path and method */
type OpOf<Paths, Path extends keyof Paths, Method extends string> = Paths[Path] extends {
  [K in Method]: infer Op;
}
  ? NonNullable<Op>
  : never;

// Infer formats from the option properties, then validate their required presence.
type OperationOptions<
  Op,
  Format extends OpenApiResponseType,
  Observe extends OpenApiObserve,
> = OpenApiOperationRequest<Op> & { responseType?: Format; observe?: Observe } & NoInfer<
    OpenApiHttpRequestOptions<Format, Observe>
  >;

type RequestShape = OpenApiHttpRequestOptions<OpenApiResponseType, OpenApiObserve> & {
  params?: {
    path?: Record<string, string | number | boolean>;
    query?: Record<string, string | number | boolean | null | undefined>;
  };
  body?: unknown;
};

/**
 * A type-safe HTTP client for OpenAPI-described APIs.
 *
 * Wraps Angular's `HttpClient` and binds paths, parameters, request bodies and
 * JSON response types to a schema generated by `openapi-typescript`.
 *
 * Requests default to `responseType: 'json'` and `observe: 'body'`. Select
 * `'blob'`, `'arraybuffer'` or `'text'` for raw responses, and `'response'` or
 * `'events'` to receive a typed `HttpResponse` or `HttpEvent` stream instead
 * of the body. These options follow Angular's return types.
 *
 * By default, injects Angular's configured `HttpClient`, requiring an injection
 * context. Supplying `config.httpClient` uses that instance without injection,
 * so construction outside an injection context is supported.
 *
 * Designed to be subclassed per-API:
 *
 * @example
 * ```ts
 * import type { paths } from './api.types'; // generated by openapi-typescript
 *
 * @Injectable({ providedIn: 'root' })
 * export class PetApiClient extends OpenApiHttpClient<paths> {
 *   constructor() {
 *     super({ baseUrl: 'https://api.example.com' });
 *   }
 * }
 * ```
 *
 * Or used directly inside an injection context:
 *
 * @example
 * ```ts
 * const client = new OpenApiHttpClient<paths>({ baseUrl: 'https://api.example.com' });
 * ```
 */
export class OpenApiHttpClient<Paths extends PathRecord> {
  private readonly http: HttpClient;
  private readonly baseUrl: string;

  constructor(config?: OpenApiHttpClientConfig) {
    this.http = config?.httpClient ?? inject(HttpClient);
    this.baseUrl = config?.baseUrl ?? '';
  }

  /**
   * Performs a typed GET request.
   *
   * @example
   * ```ts
   * client.get('/pets', { params: { query: { limit: 10 } } }).subscribe(pets => console.log(pets));
   * ```
   *
   * @example
   * ```ts
   * client.get('/documents/{id}', {
   *   params: { path: { id: 123 } },
   *   responseType: 'blob',
   *   observe: 'response',
   * }); // Observable<HttpResponse<Blob>>
   * ```
   */
  get<Path extends PathsWithMethod<Paths, 'get'> & keyof Paths>(
    path: Path,
    options?: OpenApiOperationRequest<OpOf<Paths, Path, 'get'>> & OpenApiHttpRequestOptions,
  ): Observable<OpenApiResponseBody<OpOf<Paths, Path, 'get'>>>;

  /** Performs a typed GET request with explicit response decoding or observation options. */
  get<
    Path extends PathsWithMethod<Paths, 'get'> & keyof Paths,
    Format extends OpenApiResponseType = 'json',
    Observe extends OpenApiObserve = 'body',
  >(
    path: Path,
    options: OperationOptions<OpOf<Paths, Path, 'get'>, Format, Observe>,
  ): Observable<
    OpenApiObservedValue<OpenApiResponseBody<OpOf<Paths, Path, 'get'>, Format>, Observe>
  >;

  get(path: PathsWithMethod<Paths, 'get'> & keyof Paths, options?: unknown): Observable<unknown> {
    return this.send('GET', String(path), options);
  }

  /**
   * Performs a typed POST request.
   */
  post<Path extends PathsWithMethod<Paths, 'post'> & keyof Paths>(
    path: Path,
    options?: OpenApiOperationRequest<OpOf<Paths, Path, 'post'>> & OpenApiHttpRequestOptions,
  ): Observable<OpenApiResponseBody<OpOf<Paths, Path, 'post'>>>;

  /** Performs a typed POST request with explicit response decoding or observation options. */
  post<
    Path extends PathsWithMethod<Paths, 'post'> & keyof Paths,
    Format extends OpenApiResponseType = 'json',
    Observe extends OpenApiObserve = 'body',
  >(
    path: Path,
    options: OperationOptions<OpOf<Paths, Path, 'post'>, Format, Observe>,
  ): Observable<
    OpenApiObservedValue<OpenApiResponseBody<OpOf<Paths, Path, 'post'>, Format>, Observe>
  >;

  post(path: PathsWithMethod<Paths, 'post'> & keyof Paths, options?: unknown): Observable<unknown> {
    return this.send('POST', String(path), options);
  }

  /**
   * Performs a typed PUT request.
   */
  put<Path extends PathsWithMethod<Paths, 'put'> & keyof Paths>(
    path: Path,
    options?: OpenApiOperationRequest<OpOf<Paths, Path, 'put'>> & OpenApiHttpRequestOptions,
  ): Observable<OpenApiResponseBody<OpOf<Paths, Path, 'put'>>>;

  /** Performs a typed PUT request with explicit response decoding or observation options. */
  put<
    Path extends PathsWithMethod<Paths, 'put'> & keyof Paths,
    Format extends OpenApiResponseType = 'json',
    Observe extends OpenApiObserve = 'body',
  >(
    path: Path,
    options: OperationOptions<OpOf<Paths, Path, 'put'>, Format, Observe>,
  ): Observable<
    OpenApiObservedValue<OpenApiResponseBody<OpOf<Paths, Path, 'put'>, Format>, Observe>
  >;

  put(path: PathsWithMethod<Paths, 'put'> & keyof Paths, options?: unknown): Observable<unknown> {
    return this.send('PUT', String(path), options);
  }

  /**
   * Performs a typed PATCH request.
   */
  patch<Path extends PathsWithMethod<Paths, 'patch'> & keyof Paths>(
    path: Path,
    options?: OpenApiOperationRequest<OpOf<Paths, Path, 'patch'>> & OpenApiHttpRequestOptions,
  ): Observable<OpenApiResponseBody<OpOf<Paths, Path, 'patch'>>>;

  /** Performs a typed PATCH request with explicit response decoding or observation options. */
  patch<
    Path extends PathsWithMethod<Paths, 'patch'> & keyof Paths,
    Format extends OpenApiResponseType = 'json',
    Observe extends OpenApiObserve = 'body',
  >(
    path: Path,
    options: OperationOptions<OpOf<Paths, Path, 'patch'>, Format, Observe>,
  ): Observable<
    OpenApiObservedValue<OpenApiResponseBody<OpOf<Paths, Path, 'patch'>, Format>, Observe>
  >;

  patch(
    path: PathsWithMethod<Paths, 'patch'> & keyof Paths,
    options?: unknown,
  ): Observable<unknown> {
    return this.send('PATCH', String(path), options);
  }

  /**
   * Performs a typed DELETE request.
   */
  delete<Path extends PathsWithMethod<Paths, 'delete'> & keyof Paths>(
    path: Path,
    options?: OpenApiOperationRequest<OpOf<Paths, Path, 'delete'>> & OpenApiHttpRequestOptions,
  ): Observable<OpenApiResponseBody<OpOf<Paths, Path, 'delete'>>>;

  /** Performs a typed DELETE request with explicit response decoding or observation options. */
  delete<
    Path extends PathsWithMethod<Paths, 'delete'> & keyof Paths,
    Format extends OpenApiResponseType = 'json',
    Observe extends OpenApiObserve = 'body',
  >(
    path: Path,
    options: OperationOptions<OpOf<Paths, Path, 'delete'>, Format, Observe>,
  ): Observable<
    OpenApiObservedValue<OpenApiResponseBody<OpOf<Paths, Path, 'delete'>, Format>, Observe>
  >;

  delete(
    path: PathsWithMethod<Paths, 'delete'> & keyof Paths,
    options?: unknown,
  ): Observable<unknown> {
    return this.send('DELETE', String(path), options);
  }

  private send(method: string, path: string, options: unknown): Observable<unknown> {
    const request = (options ?? {}) as RequestShape;
    const result: Observable<unknown> = this.http.request(
      method,
      buildUrl(this.baseUrl, path, request.params?.path),
      {
        body: request.body,
        params: toHttpParams(request.params?.query),
        headers: request.headers as HttpHeaders | Record<string, string | string[]> | undefined,
        context: request.context,
        withCredentials: request.withCredentials,
        reportProgress: request.reportProgress,
        responseType: request.responseType ?? 'json',
        observe: request.observe ?? 'body',
      },
    );
    return result;
  }
}
